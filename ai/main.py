import math
from flask import Flask, request, jsonify
import numpy as np
from sklearn.preprocessing import MinMaxScaler

app = Flask(__name__)


@app.get('/health')
def health():
    return jsonify(success=True, message='PathCraft AI service is running', model='scikit-learn-v1.5')


@app.post('/recommend')
def recommend_routes():
    """
    Ranks candidate routes generated by OSRM based on target metrics and user preferences.
    Uses scikit-learn feature normalization and multi-objective scoring.
    """
    try:
        data = request.get_json(force=True, silent=True) or {}
        activity = data.get('activity', 'running').lower()
        target_distance = float(data.get('targetDistanceKm', 5.0))
        preferences = data.get('preferences', {})
        routes = data.get('routes', [])

        if not routes:
            return jsonify(success=True, rankedRoutes=[], message='No candidate routes provided')

        # Weights based on activity & preferences
        prefer_loop = bool(preferences.get('preferLoop', True))
        avoid_major_roads = bool(preferences.get('avoidMajorRoads', True))
        prefer_sidewalks = bool(preferences.get('preferSidewalks', True))
        prefer_cycling_lanes = bool(preferences.get('preferCyclingInfrastructure', activity == 'cycling'))

        scored_routes = []
        raw_features = []

        for r in routes:
            dist = float(r.get('distanceKm', target_distance))
            duration = float(r.get('durationSeconds', dist * 360))
            features = r.get('features', {})

            # Distance accuracy: penalty for differing from target
            dist_diff = abs(dist - target_distance)
            dist_score = max(0.0, 100.0 - (dist_diff / max(target_distance, 1.0)) * 100.0)

            # Feature scores
            is_loop = 1.0 if features.get('isLoop', False) else 0.0
            sidewalk_ratio = float(features.get('sidewalkRatio', 0.8))
            major_road_ratio = float(features.get('majorRoadRatio', 0.1))
            cycling_lane_ratio = float(features.get('cyclingLaneRatio', 0.7 if activity == 'cycling' else 0.3))

            pref_score = 70.0
            if prefer_loop and is_loop:
                pref_score += 15.0
            if avoid_major_roads:
                pref_score += (1.0 - major_road_ratio) * 10.0
            if prefer_sidewalks:
                pref_score += sidewalk_ratio * 10.0
            if prefer_cycling_lanes:
                pref_score += cycling_lane_ratio * 10.0

            pref_score = min(100.0, max(20.0, pref_score))

            raw_features.append([dist_score, pref_score, 100.0 - (major_road_ratio * 100.0)])
            scored_routes.append({
                'route': r,
                'dist_score': dist_score,
                'pref_score': pref_score,
            })

        # Feature scaling with scikit-learn
        if len(raw_features) > 1:
            scaler = MinMaxScaler(feature_range=(50, 100))
            scaled = scaler.fit_transform(np.array(raw_features))
            for i, item in enumerate(scored_routes):
                item['final_score'] = float(np.mean(scaled[i]))
        else:
            scored_routes[0]['final_score'] = float((scored_routes[0]['dist_score'] * 0.6) + (scored_routes[0]['pref_score'] * 0.4))

        # Sort descending by final score
        scored_routes.sort(key=lambda x: x['final_score'], reverse=True)

        ranked = []
        for idx, item in enumerate(scored_routes):
            r = item['route']
            score = round(item['final_score'], 1)
            
            # Categorize match quality
            if score >= 85:
                suitability = 'Excellent match'
                match_label = 'Best Match'
            elif score >= 70:
                suitability = 'Good match'
                match_label = 'Recommended'
            else:
                suitability = 'Fair match'
                match_label = 'Alternative'

            # Recommendation reason
            dist_km = r.get('distanceKm', target_distance)
            reasons = []
            if abs(dist_km - target_distance) <= 0.3:
                reasons.append(f'Matches target {target_distance} km closely')
            if item['route'].get('features', {}).get('isLoop', False):
                reasons.append('Complete loop circuit')
            if avoid_major_roads:
                reasons.append('Low traffic / pedestrian-friendly')
            if not reasons:
                reasons.append(f'Suitable for {activity}')

            r_copy = dict(r)
            r_copy['score'] = score
            r_copy['rank'] = idx + 1
            r_copy['isTopRecommendation'] = (idx == 0)
            r_copy['suitability'] = suitability
            r_copy['matchLabel'] = match_label
            r_copy['reasoning'] = ' • '.join(reasons)
            ranked.append(r_copy)

        return jsonify(
            success=True,
            rankedRoutes=ranked,
            totalRanked=len(ranked),
            activity=activity,
            targetDistanceKm=target_distance
        )

    except Exception as e:
        return jsonify(success=False, error=str(e)), 500


if __name__ == '__main__':
    app.run(host='0.0.0.0', port=8000)
